#include<iostream>
using namespace std;
int main(){
    int a,b;
    cout<<"Enter first number:";
    cin>>a; //input first number
    cout<<"Enter second number:";
    cin>>b; //input second number
    cout<<"First number is : "<<a<<endl; //output first number
    cout<<"Second number is : "<<b<<endl; //output second number
    return 0; //return 0 to indicate successful execution
}

// This code demonstrates how to take user input in C++
// It uses the 'cin' object to read input from the user and 'cout' to
// display output to the console