//varibale is a name given to a memory location
#include<iostream>
using namespace std;
int main() {
    int a = 10; // integer variable named 'a'
    float b = 5.5; // float variable named 'b'
    // Variables can store different types of data
    char c = 'A'; // character variable
    string d = "Hello"; // string variable

    cout << "Integer: " << a << endl;
    cout << "Float: " << b << endl;
    cout << "Character: " << c << endl;
    cout << "String: " << d << endl;

    return 0;
}

//variables is called as a container or identifier
